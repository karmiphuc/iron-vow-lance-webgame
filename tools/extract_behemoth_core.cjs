// Reuse Gatecrasher R2's authored torso and cockpit on the Foundry tetrapod.
// Run from the checkout: node tools/extract_behemoth_core.cjs
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const T=require('../dist/rig-bench/vendor/three.min.js');
const {createCanvas,loadImage}=require('../qa/node_modules/@napi-rs/canvas');
global.THREE=T;global.self=global;
global.document={createElement:()=>createCanvas(1,1)};
global.createImageBitmap=async blob=>loadImage(Buffer.from(await blob.arrayBuffer()));
require('../dist/rig-bench/vendor/GLTFLoader.js');
const source=fs.readFileSync(path.join(__dirname,'../dist/rig-bench/prototypes/gatecrasher.glb'));
// The pilot target is on the forward viewing slit; the inset cabin stays fixed.
const fit={scale:1.012,offset:[0,.08,-.05],pilot:[0,1.52716,1.15736]};
const pack=array=>Buffer.from(array.buffer,array.byteOffset,array.byteLength).toString('base64');
new T.GLTFLoader().parse(source.buffer.slice(source.byteOffset,source.byteOffset+source.byteLength),'',g=>{
 g.scene.updateMatrixWorld(true);
 let torso;g.scene.traverse(o=>{if(o.userData.name==='Torso')torso=o});
 if(!torso)throw Error('Gatecrasher torso bone is missing');
 const inverse=torso.matrixWorld.clone().invert(),meshes=[];
 g.scene.traverse(o=>{
  const name=o.parent?.userData.name;
  if(!o.isSkinnedMesh||!['Torso / rigid assembly','Optics / rigid assembly'].includes(name))return;
  const part=name.startsWith('Optics')?'pilot':'body',a=o.geometry.attributes;
  o.skeleton.update();
  const bone=a.skinIndex.getX(0);
  for(let i=0;i<a.position.count;i++)if(a.skinIndex.getX(i)!==bone||a.skinWeight.getX(i)<.9999)throw Error('Expected a rigid torso assembly');
  const matrix=inverse.clone().multiply(o.matrixWorld).multiply(o.bindMatrixInverse)
   .multiply(o.skeleton.bones[bone].matrixWorld).multiply(o.skeleton.boneInverses[bone]).multiply(o.bindMatrix);
  const normalMatrix=new T.Matrix3().getNormalMatrix(matrix),p=new T.Vector3(),n=new T.Vector3();
  const positions=new Int16Array(a.position.count*3),normals=new Int8Array(a.position.count*3),uvs=new Float32Array(a.position.count*2);
  for(let i=0;i<a.position.count;i++){
   p.fromBufferAttribute(a.position,i).applyMatrix4(matrix).multiplyScalar(fit.scale).add(new T.Vector3(...fit.offset));
   if(part==='pilot')p.sub(new T.Vector3(...fit.pilot));
   n.fromBufferAttribute(a.normal,i).applyMatrix3(normalMatrix).normalize();
   for(let c=0;c<3;c++){
    const value=Math.round(p.getComponent(c)*4096);
    if(Math.abs(value)>32767)throw Error('Core exceeded packed position bounds');
    positions[i*3+c]=value;normals[i*3+c]=Math.round(n.getComponent(c)*127);
   }
   uvs[i*2]=a.uv?.getX(i)||0;uvs[i*2+1]=a.uv?.getY(i)||0;
  }
  const index=Uint16Array.from(o.geometry.index?.array??Array.from({length:a.position.count},(_,i)=>i));
  meshes.push({part,material:o.material.name.split(' / ').at(-1),positions:pack(positions),normals:pack(normals),uvs:pack(uvs),index:pack(index)});
 });
 if(meshes.length!==14)throw Error('Expected eight torso and six cockpit material groups');
 const data={source:'Gatecrasher R2 torso and inset crew cabin',sha256:crypto.createHash('sha256').update(source).digest('hex'),fit,meshes};
 fs.writeFileSync(path.join(__dirname,'../dist/foundry/behemoth-core.js'),'/* Generated by tools/extract_behemoth_core.cjs; geometry only, no Gatecrasher weapons or legs. */\nwindow.IronVowBehemothCore='+JSON.stringify(data)+';\n');
 console.log('Extracted',meshes.length,'Gatecrasher core material groups');
},error=>{console.error(error);process.exitCode=1});
