const assert=require('node:assert/strict');
const simulate=require('./sim-harness.cjs');
const key='iron-vow-career';
const career=sim=>JSON.parse(sim.storage.get(key));
const resume=sim=>simulate({storage:new Map(sim.storage),random:()=>.99,reducedMotion:true});
const resolve=(run,win=true)=>run(`for(const u of battle.units)if(u.team==='enemy'){u.alive=false;u.hp.body=0}finish(${win});closeModal()`);

(async()=>{
 const sim=simulate({random:()=>0,reducedMotion:true}),run=sim.run;
 run('persist()');
 assert.equal(career(sim).ship,undefined);
 assert.equal(career(sim).wounds,undefined);
 assert.equal(run('queueShipUpgrade("office")'),true);
 assert.equal(run('queueShipUpgrade("repair")'),false);
 assert.equal(run('save.credits'),2700);
 assert.deepEqual(career(resume(sim)).ship,{levels:{},project:{facility:'office',wins:1}});
 run('createBattle(0,false,false,[0])');
 resolve(run,false);
 assert.equal(run('save.ship.project.wins'),1);
 run('createBattle(0,false,false,[0])');
 resolve(run);
 assert.equal(run('save.history.at(-1).pay'),1300,'new upgrade activates after the payout');
 assert.equal(run('shipLevel("office")'),1);
 assert.equal(run('contractPay(CONTRACTS[0],1)'),1495);
 run('save.credits=20000');
 assert.equal(run('queueShipUpgrade("office")'),false,'rank 2 needs reputation');
 run('save.rep=30;save.credits=0');
 assert.equal(run('queueShipUpgrade("office")'),false,'rank 2 needs credits');
 run('save.credits=20000');
 assert.equal(run('queueShipUpgrade("office")'),true);
 run('createBattle(0,false,false,[0])');resolve(run);
 assert.equal(run('save.ship.project.wins'),1);
 assert.equal(run('shipLevel("office")'),1);
 run('createBattle(0,false,false,[0])');resolve(run);
 assert.equal(run('shipLevel("office")'),2);
 assert.equal(run('contractPay(CONTRACTS[0],1)'),1625);
 for(const ship of [{levels:{drop:3}},{levels:{unknown:1}},{levels:{drop:2},project:{facility:'drop',wins:1}},{levels:{},project:{facility:'crew',wins:2}}]){
  assert.equal(run('validSave({...save,ship:'+JSON.stringify(ship)+'})'),false);
 }

 const crew=simulate({random:()=>0,reducedMotion:true}),play=crew.run;
 play('save.credits=FRAMES[6].cost+20000;hirePilot(3);acquireHull(6);save.reserve[6].condition=35;save.units[1].condition=60;createBattle(0,false,false,[0]);battle.units[0].hp.pilot=0;battle.units[0].alive=false');
 resolve(play,false);
 assert.equal(play('woundDays("rook")'),2);
 assert.equal(play('assignPilot(1,0)'),false,'active pilots cannot be duplicated');
 assert.equal(play('assignPilot(0,3)'),true);
 play('createBattle(0,false,false,[2]);selected=2');resolve(play,false);
 assert.equal(play('woundDays("rook")'),1,'rest follows pilot into reserve');
 assert.equal(play('assignPilot(1,0)'),true);
 play('createBattle(0,false,false,[1]);selected=1');
 assert.equal(play('battle.units[0].hp.pilot'),play('Math.ceil(battle.units[0].max.pilot*.65)'));
 resolve(play,false);
 assert.equal(play('woundDays("rook")'),1,'conscious deployment does not rest without Simulator Pods');
 play('save.wounds.rook=2;save.ship={levels:{crew:1,repair:1}};createBattle(0,false,false,[0]);selected=0');
 resolve(play);
 assert.equal(play('woundDays("rook")'),0);
 assert.equal(play('save.units[1].condition'),72);
 assert.equal(play('save.reserve[6].condition'),47);
 assert.equal(play('repairCost(1)'),314);
 play('save.ship.levels={crew:2,repair:2};save.wounds.rook=2;createBattle(0,false,false,[1]);selected=1;let flown=battle.units[0];const benchXP=save.units[2].xp,reserveXP=save.reservePilots.ghost.xp;let beforeHull=100*(flown.hp.body+flown.hp.right+flown.hp.left+flown.hp.legs)/(flown.max.body+flown.max.right+flown.max.left+flown.max.legs)');
 resolve(play);
 assert.equal(play('woundDays("rook")'),0);
 assert.equal(play('save.units[1].condition'),play('Math.min(100,Math.round(beforeHull)+8)'));
 assert.equal(play('save.reserve[6].condition'),71);
 assert.equal(play('save.units[2].xp-benchXP'),25);
 assert.equal(play('save.reservePilots.ghost.xp-reserveXP'),25);

 const aux=simulate({random:()=>.99,reducedMotion:true}),fly=aux.run;
 fly('save.credits=FRAMES[6].cost+30000;save.rep=30;hirePilot(3);acquireHull(6);save.reserve[6].paint="#193857";save.reserve[6].condition=85;Object.assign(save.reservePilots.scout,{level:3,training:["scout-optics"]});save.ship={levels:{drop:2,office:1}};const seat={pilotId:"scout",frame:6}');
 assert.equal(fly('validAux(seat)'),true);
 assert.equal(fly('validAux({...seat,pilotId:"rook"})||validAux({...seat,frame:0})'),false);
 for(let contract=0;contract<4;contract++)for(let count=1;count<=3;count++){
  fly(`createBattle(${contract},false,false,LANCE_SLOTS.slice(0,${count}),true,seat);selected=3;persist()`);
  const checkpoint=career(aux).sortie;
  assert.equal(checkpoint.version,8);
  assert.equal(checkpoint.slots.length,count+1);
  assert.equal(fly('battle.units.filter(u=>u.team==="enemy").length'),fly(`sortieSpawns(CONTRACTS[${contract}],${count}).length`));
  assert.equal(fly('battle.cover.has("3,18")'),false);
  assert.equal(fly('current().paint'), '#193857');
  assert.equal(fly('current().level'),3);
  assert.equal(fly('current().ap-roundAP(current().training)'),1);
  assert.deepEqual(JSON.parse(resume(aux).run('JSON.stringify(captureSortie())')),checkpoint);
 }
 const damaged=career(aux);
 damaged.reserve[6].condition=29;
 assert.equal(simulate({storage:new Map([[key,JSON.stringify(damaged)]])}).run('battle'),null);
 fly('createBattle(0,false,false,[0,1,2],true,seat);selected=0;let ghost=battle.units[1];ghost.hp.body=0;ghost.alive=false;ghost.downReason="body"');
 await fly('endTurn()');
 assert.equal(fly('battle.turn'),2);
 assert.equal(fly('ghost.ap'),9);
 assert.deepEqual(JSON.parse(resume(aux).run('JSON.stringify(captureSortie())')),career(aux).sortie,'dead pilot retains launch AP in later checkpoints');
 fly('createBattle(0,false,false,[0],true,seat);selected=3;const beforeHull=battle.units[1].hp.body;battle.units[1].hp.body=0;const baseXP=save.units[0].xp');
 resolve(fly);
 assert.equal(fly('save.history.at(-1).pay'),1495);
 assert.equal(fly('save.reservePilots.scout.xp'),70);
 assert.ok(fly('save.reserve[6].condition<85'));
 assert.equal(fly('save.units[0].xp-baseXP'),70);
 assert.equal(fly('save.units[1].xp'),0);
 assert.equal(fly('selected'),0);
 console.log('PASS: ship construction, payout timing, crew wounds and recovery, hull service, and v8 auxiliary sorties across all contracts.');
})().catch(error=>{console.error(error);process.exitCode=1});
