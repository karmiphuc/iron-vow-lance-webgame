const assert=require('node:assert/strict');

module.exports=async function checkDutyRoster({page,mobile,origin,tap}){
 const nav=view=>tap('#nav [data-page="'+view+'"]');
 const ids=['scout','marshal','sapper','signal','retriever'];
 await page.goto(new URL('?view=inn',origin).href,{waitUntil:'domcontentloaded'});
 await page.locator('[data-hire="7"]').waitFor();
 const images=page.locator('.inn-pilot img.recruit-portrait');
 assert.equal(await images.count(),5);
 await page.waitForFunction(()=>[...document.querySelectorAll('.inn-pilot img.recruit-portrait')].every(img=>img.complete&&img.naturalWidth>0));
 assert.deepEqual(await images.evaluateAll(imgs=>imgs.map(img=>img.getAttribute('src'))),ids.map(id=>'assets/pilot-'+id+'.png'));
 await page.evaluate(()=>{
  save.credits=30000;save.rep=50;
  save.history=[{name:CONTRACTS[0].name,day:1,win:true,pay:1300}];
  persist();render();
 });
 for(let kind=3;kind<8;kind++)await tap('[data-hire="'+kind+'"]');
 await nav('hangar');
 assert.match(await page.locator('#duty-count').innerText(),/3 \/ 3/);
 await tap('[data-build-room="cabins"]');
 await nav('contracts');
 await tap('[data-deploy="0"]');
 await tap('#modal-1');
 await page.evaluate(()=>{for(const u of battle.units)if(u.team==='enemy'){u.alive=false;u.hp.body=0}finish(true);closeModal()});
 await nav('hangar');
 assert.match(await page.locator('#duty-count').innerText(),/3 \/ 4/);
 await tap('[data-pilot-duty="scout"]');
 assert.ok(await page.locator('[data-pilot-duty="sapper"]').isDisabled());
 await page.evaluate(()=>{save.hangar.levels.cabins=3;persist();render()});
 for(const id of ['sapper','signal'])await tap('[data-pilot-duty="'+id+'"]');
 assert.match(await page.locator('#duty-count').innerText(),/6 \/ 6/);
 assert.ok(await page.locator('[data-pilot-duty="retriever"]').isDisabled());
 await nav('pilots');
 assert.equal(await page.locator('.pilot-card').count(),6);
 await tap('[data-reserve-training="scout"]');
 await tap('[data-learn="scout-optics"]');
 await tap('#modal-0');
 await page.evaluate(()=>{
  save.ship={levels:{drop:2}};acquireHull(6);
  save.dispatch={day:save.day,sizes:[3,2,1,3]};persist();
 });
 await nav('contracts');
 await tap('[data-deploy="0"]');
 assert.equal(await page.locator('[data-sortie-pilot="0"] option').count(),6);
 await page.locator('[data-sortie-pilot="0"]').selectOption('scout');
 await tap('#modal-0');
 assert.equal(await page.evaluate(()=>pilotProfile(0).call),'ROOK');
 await tap('[data-deploy="0"]');
 await page.locator('[data-sortie-pilot="0"]').selectOption('scout');
 await page.locator('[data-sortie-pilot="1"]').selectOption('signal');
 assert.equal(await page.locator('[data-sortie-pilot="1"] option[value="scout"]').evaluate(option=>option.disabled),true);
 assert.equal(await page.locator('#aux-pilot option[value="scout"]').evaluate(option=>option.disabled),true);
 await page.locator('#aux-pilot').selectOption('marshal');
 await tap('#use-aux');
 assert.ok(await page.locator('.modalbox').evaluate(e=>e.scrollWidth<=e.clientWidth+1),mobile?'mobile assignment fits':'desktop assignment fits');
 await tap('#modal-1');
 assert.equal(await page.locator('.unitbuttons button').count(),4);
 assert.equal(await page.evaluate(()=>battle.units.filter(u=>u.team==='ally').map(u=>pilotId(u.pilot)).join()),'scout,signal,anchor,marshal');
 assert.equal(await page.evaluate(()=>battle.units[0].training.paintRange),2);
 const saved=await page.evaluate(async()=>{await pendingCareerWrite;return JSON.parse(await readCareerDB(careerDB))});
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('[data-unit="3"]').waitFor();
 assert.equal(await page.evaluate(()=>activeRosterIds().length),6);
 assert.deepEqual(await page.evaluate(()=>JSON.parse(JSON.stringify(captureSortie()))),saved.sortie);
};
