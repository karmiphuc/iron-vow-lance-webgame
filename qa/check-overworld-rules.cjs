const assert=require('node:assert/strict');
global.window={};
require('../dist/overworld.js');
const {PORTS,ROUTES,operatingRates,travelQuote,settleExpenses,validState}=window.IronVowOverworld;

const fresh={units:Array.from({length:3},()=>({level:1,upgrade:0}))};
assert.deepEqual(operatingRates(fresh),{wages:210,ship:75,hulls:105,total:390});
const expanded={units:[{level:3,upgrade:2}],reservePilots:{one:{level:2},two:{level:1}},reserve:{4:{upgrade:3}},ship:{levels:{bridge:2,drop:1}}};
assert.deepEqual(operatingRates(expanded),{wages:240,ship:135,hulls:85,total:460});
assert.equal(PORTS.length,4);
assert.equal(ROUTES.length,4);
const rates=operatingRates(fresh);
assert.deepEqual(travelQuote('picket','relay',rates),{days:1,fuel:120,wages:210,ship:75,hulls:105,total:510});
assert.deepEqual(travelQuote('frontier','corridor',rates),{days:2,fuel:260,wages:420,ship:150,hulls:210,total:1040});
assert.equal(travelQuote('picket','frontier',rates),null);
assert.equal(travelQuote('picket','picket',rates),null);
assert.deepEqual(settleExpenses(1000,200,390),{credits:410,arrears:0,paid:390,arrearsPaid:200});
assert.deepEqual(settleExpenses(500,200,390),{credits:0,arrears:90,paid:390,arrearsPaid:110});
assert.deepEqual(settleExpenses(100,200,390),{credits:0,arrears:490,paid:100,arrearsPaid:0});
assert.deepEqual(settleExpenses(500.75,200,390),{credits:0.75,arrears:90,paid:390,arrearsPaid:110});
assert.deepEqual(settleExpenses(0.75,Number.MAX_SAFE_INTEGER,390),{credits:0.75,arrears:Number.MAX_SAFE_INTEGER,paid:0,arrearsPaid:0});
const expense={kind:'travel',day:1,days:1,fuel:120,wages:210,ship:75,hulls:105,total:510,paid:510,arrearsPaid:0,destination:'relay'};
assert.equal(validState({port:'picket',arrears:0}),true);
assert.equal(validState({port:'relay',arrears:0,lastExpense:expense}),true);
const sortie={...expense,kind:'sortie',fuel:0,total:390,paid:100,destination:undefined};
assert.equal(validState({port:'picket',arrears:0,lastExpense:sortie}),true);
for(const bad of [{...expense,destination:undefined},{...expense,paid:509},{...expense,arrearsPaid:1},{...expense,total:511},{...sortie,days:2},{...sortie,fuel:1},{...sortie,paid:391},{...sortie,destination:'relay'}])assert.equal(validState({port:'picket',arrears:0,lastExpense:bad}),false);
for(const state of [null,[],{port:'unknown',arrears:0},{port:'picket',arrears:-1},{port:'picket',arrears:Number.MAX_SAFE_INTEGER+1},{port:'picket',arrears:0,lastExpense:{...expense,day:0}},{port:'picket',arrears:0,lastExpense:{...expense,paid:1.5}},{port:'picket',arrears:0,lastExpense:{...expense,destination:'unknown'}},{port:'picket',arrears:0,lastExpense:{...expense,kind:'sortie'}}])assert.equal(validState(state),false);
console.log('Overworld rules: all checks passed');
