const assert=require('node:assert/strict');
const {createSampler}=require('../dist/performance.js');
const sampler=createSampler(4);
for(const time of [0,10,30,60,100,150])sampler.begin(time);
sampler.record({render:{calls:3,triangles:120}});
sampler.record({render:{calls:2,triangles:80}});
sampler.end({contexts:2,geometries:15,textures:4});
let report=sampler.report();
assert.equal(report.samples,4);
assert.deepEqual(report.frameMs,{p50:30,p95:50});
assert.equal(report.fps,1000/35);
assert.equal(report.calls,5,'Count every offscreen render, not only the last mech');
assert.equal(report.triangles,200);
assert.equal(report.contexts,2);
sampler.begin(160);
sampler.end({contexts:0,geometries:0,textures:0});
report=sampler.report();
assert.equal(report.calls,0,'Cached/composited frames have no new WebGL calls');
assert.equal(report.geometries,0,'Disposed contexts do not keep reporting old memory');
sampler.reset();sampler.begin(20000);
assert.equal(sampler.report().frameMs.p95,null,'Background-tab time is excluded after reset');
sampler.end({contexts:1});sampler.record({render:{calls:7,triangles:90}});sampler.begin(20016);sampler.end({contexts:1});
assert.equal(sampler.report().calls,7,'Asynchronous preview renders between animation frames are counted');
console.log('PASS bounded frame percentiles, all-render WebGL totals, disposal and visibility reset');
