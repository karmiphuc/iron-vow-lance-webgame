const assert=require('node:assert/strict');
const simulate=require('./sim-harness.cjs');
const careerKey='iron-vow-career';
const backup=sim=>JSON.parse(sim.storage.get(careerKey));

(async()=>{
 const sim=simulate({random:()=>0,reducedMotion:true}),run=sim.run;
 run("save.units[0].level=3;save.units[0].xp=72;learnTraining(0,'pathfinder');learnTraining(0,'point-plate');save.units[0].paint='#112233';save.units[0].condition=79;persist()");
 const legacy=backup(sim);
 assert.equal(legacy.reservePilots,undefined);
 assert.equal(legacy.units[0].pilotId,undefined);
 const imported=simulate({storage:new Map([[careerKey,JSON.stringify(legacy)]])});
 assert.equal(imported.run('pilotProfile(0).call'),'ROOK');
 assert.equal(imported.run('save.units[0].xp'),72);
 assert.equal(run('hirePilot(3)&&hirePilot(4)'),true);
 assert.equal(run('save.credits'),1900);
 assert.equal(run('hirePilot(3)'),false);
 assert.equal(run('assignPilot(0,3)&&assignPilot(2,4)'),true);
 assert.equal(run('learnTraining(0,"scout-optics")'),true);
 assert.equal(run('learnTraining(2,"marshal-link")'),true);
 assert.equal(run('save.units[0].paint'),'#112233');
 assert.equal(run('save.units[0].condition'),79);
 assert.deepEqual(backup(sim).reservePilots.rook,{level:3,xp:72,training:['pathfinder','point-plate']});
 assert.equal(run('assignChassis(0,2,true)'),true);
 assert.equal(run('pilotProfile(0).call'), 'SCOUT');
 assert.equal(run('save.units[2].paint'),'#112233');
 const reload=simulate({storage:new Map(sim.storage)});
 assert.equal(reload.run('pilotProfile(2).call'),'MARSHAL');
 assert.equal(reload.run('assignPilot(1,0)'),true);
 assert.equal(reload.run('save.units[1].xp'),72);
 assert.equal(reload.run('learnedTraining(1).join()'),'pathfinder,point-plate');
 assert.equal(reload.run('save.reservePilots.ghost.level'),1);
 assert.equal(reload.run('validSave({...save,reservePilots:{...save.reservePilots,rook:{level:1,xp:0,training:[]}}})'),false);
 console.log('PASS: legacy career, both hires, duplicate protection, identity and training on seat and hull swaps.');

 const rolls=simulate();
 rolls.run('let rolls=[.01,.4,.99,.61];Math.random=()=>rolls.shift();dispatchSizes()');
 assert.deepEqual(backup(rolls).dispatch.sizes,[1,2,3,2]);
 const stable=simulate({storage:new Map(rolls.storage),random:()=>0});
 assert.equal(stable.run('dispatchSizes().join()'),'1,2,3,2');
 for(const [slots,index] of [[[2],0],[[0,2],1],[[0,1,2],2]]){
  run(`battle=null;createBattle(${index},false,false,${JSON.stringify(slots)});selected=${slots[0]};persist()`);
  const state=backup(sim).sortie,loaded=simulate({storage:new Map(sim.storage)});
  assert.equal(state.version,7);
  assert.deepEqual(state.slots,slots);
  assert.equal(loaded.run('battle.slots.join()'),slots.join());
  assert.deepEqual(JSON.parse(loaded.run('JSON.stringify(captureSortie())')),state);
 }
 console.log('PASS: deterministic reload of daily offers and exact one-, two- and three-mech checkpoints.');

 run('battle=null;createBattle(1,false,false,[0,2]);let scout=battle.units[0],marshal=battle.units[1],foe=battle.units[2];selected=0');
 assert.equal(run('useSupportSkill(scout,foe)'),false,'range checked at resolution');
 run('foe.x=1;foe.z=12;let prior=hitChance(scout,foe,"pilot");selected=0');
 assert.equal(run('useSupportSkill(scout,foe)'),true);
 assert.ok(run('hitChance(scout,foe,"pilot")>prior'));
 assert.equal(run('useSupportSkill(scout,foe)'),false);
 run('selected=2');
 assert.equal(run('useSupportSkill(marshal,scout)'),true);
 assert.equal(run('marshal.ap'),7);
 assert.equal(run('paidAttackAP(scout,unitWeapon(scout))'),2);
 const support=simulate({storage:new Map(sim.storage),random:()=>.999,reducedMotion:true});
 const v31=backup(sim);
 v31.sortie.version=6;
 const migrated=simulate({storage:new Map([[careerKey,JSON.stringify(v31)]])});
 assert.equal(migrated.run('battle.slots.join()'),'0,2');
 assert.equal(migrated.run('battle.units[0].order.discount'),2);
 assert.equal(migrated.run('battle.units[2].painted.aim'),.20);
 const play=support.run;
 play('let [s,m,e]=battle.units');
 assert.equal(play('s.order.shots'),1);
 assert.equal(play('e.painted.aim'),.20);
 await play('shoot(s,e,"pilot",unitWeapon(s),true)');
 assert.equal(play('s.ap'),8);
 assert.equal(play('s.order.shots'),1,'reaction does not spend an order');
 assert.equal(play('e.painted'),undefined,'reaction attempt consumes a paint charge');
 await play('shoot(s,e,"pilot",unitWeapon(s))');
 assert.equal(play('s.ap'),6);
 assert.equal(play('s.order'),undefined);
 console.log('PASS: skill range, costs, checkpoint restore, paid discounts, misses and reactions.');

 run('battle=null;save.credits=12000;createBattle(2,false,false,[0],true,null,undefined,true,false);selected=0;for(const u of battle.units)if(u.team==="enemy"){u.alive=false;u.hp.body=u.kind?0:50}finish(true)');
 assert.equal(run('save.units[2].xp'),0,'benched active seat earns no XP');
 assert.equal(run('save.salvage[1]'),1);
 assert.equal(run('acquireHull(1,true)'),false,'cannot rebuild an owned hull');
 assert.equal(run('recycleHullBody(1)'),true);
 assert.equal(run('recycleHullBody(1)'),false);
 run('save.salvage[7]=1;persist()');
 const credit=run('save.credits'),cost=run('rebuildPrice(7)');
 assert.equal(run('acquireHull(7,true)'),true);
 assert.equal(run('save.credits'),credit-cost);
 assert.equal(run('save.reserve[7].condition'),55);
 assert.equal(run('save.salvage[7]'),undefined);
 assert.equal(run('acquireHull(7)'),false);
 assert.equal(run('acquireHull(6)'),true);
 assert.equal(run('save.reserve[6].condition'),100);
 assert.equal(run('pilotFrame(0)'),2,'buying and rebuilding do not change assignments');
 assert.equal(simulate({storage:new Map(sim.storage)}).run('save.reserve[6].melee'),'blade');
 console.log('PASS: recovered bodies, one-time scrap/rebuild, cold storage, and purchase without reassignment.');
})().catch(error=>{console.error(error);process.exitCode=1});
