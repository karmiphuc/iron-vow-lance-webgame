const assert=require('node:assert/strict');
const simulate=require('./sim-harness.cjs');
const career=require('./fixtures/shared-ap-sortie.json');

(async()=>{
 const sim=simulate({storage:new Map([['iron-vow-career',JSON.stringify(career)]]),reducedMotion:true,random:()=>0});
 const {run}=sim;
 assert.deepEqual(JSON.parse(run('JSON.stringify(captureSortie())')),{...career.sortie,apRules:2});
 assert.equal(run('current().ap'),9);
 assert.equal(run('current().attackAPSpent'),3);
 assert.equal(run('current().moveLeft'),3);
 assert.equal(run('battle.units[3].ap'),10);
 assert.equal(run('battle.units[3].reacted'),true);
 run('const a=current(),e=battle.units[3];a.ap=14;a.attackAPSpent=7');
 assert.equal(run("canUseWeapon(a,weapon('rifle'))"),false,'gaining shared AP does not restore the attack allowance');
 run('a.ap=0;completeRound()');
 assert.equal(run('a.ap'),12);
 assert.equal(run('attackAPLeft(a)'),8);
 assert.equal(run('a.moveLeft'),run('mobility(a)'));
 run('a.ap=9;completeRound()');
 assert.equal(run('a.ap'),14,'banked AP recovers up to capacity');

 run(`createBattle(1,true,true);battle.cover.clear();
  const caster=current(),victim=battle.units.find(u=>u.team==='enemy');
  caster.frame=VYZOV_FRAME;caster.attackAPSpent=6;
  const launcher=weapon('missile');victim.x=caster.x+1;victim.z=caster.z;
  `);
 assert.equal(run('canTactical(caster)'),false,'tactical attacks also obey the 8 AP ceiling');
 run('caster.frame=CITADEL_FRAME;caster.mechSkills=[CITADEL_FRAME];caster.attackAPSpent=5');
 const before=run('caster.ap');
 await run("engage(caster,victim,'body',launcher)");
 assert.equal(run('caster.ap'),before);
 assert.equal(run('caster.mechState?.lock'),undefined);
 run('caster.attackAPSpent=4');
 await run("engage(caster,victim,'body',launcher)");
 assert.equal(run('caster.ap'),before-4);
 assert.equal(run('caster.attackAPSpent'),8);
 assert.ok(run('caster.mechState?.lock?.turn===battle.turn'),'marking a delayed barrage spend, and chassis mobility versus APs attack AP exactly once');
 const field=simulate({reducedMotion:true,random:()=>.999}).run;
 field(`createBattle(0);surveyTerrain(1);battle.cover.clear();
  battle.field.cells.forEach(cell=>cell.level=0);
  const [warden,kestrel,basilisk]=battle.units,foe=battle.units[3];
  for(const [unit,x] of [[warden,2],[kestrel,6],[basilisk,10]])Object.assign(unit,{x,z:12,vx:x,vz:12});
  Object.assign(foe,{x:12,z:10,noCounter:true});
  const plan=(u,x,z)=>movementPlans(u).get(x+','+z);
 `);
 assert.deepEqual(Array.from(field('[warden,kestrel,basilisk].map(mobility)')),[5,6,4]);
 assert.deepEqual(Array.from(field('[warden,kestrel,basilisk].map(moveAP)')),[1,1,2]);
 assert.deepEqual(Array.from(field('[warden,kestrel,basilisk].map(u=>plan(u,u.x,8).ap)')),[4,4,8]);
 assert.deepEqual(Array.from(field("['tank','helicopter'].map(kind=>moveAP({kind}))")),[2,1]);
 field('terrainCell(10,11).level=1');
 assert.equal(field('plan(basilisk,10,11).ap'),3,'heavy movement still pays the elevation surcharge');
 field('terrainCell(10,11).level=0');
 await field('moveUnit(basilisk,10,10)');
 await field("engage(basilisk,foe,'body',unitWeapon(basilisk))");
 assert.deepEqual(Array.from(field('[basilisk.ap,basilisk.moveLeft]')),[6,2]);
 await field('moveUnit(basilisk,10,8)');
 assert.deepEqual(Array.from(field('[basilisk.ap,basilisk.moveLeft]')),[2,0]);
 assert.equal(field('plan(basilisk,10,7)'),undefined,'reserve AP cannot buy a fifth heavy movement tile');
 assert.equal(field('plan(kestrel,6,6).tiles'),6,'recon can cover the full six-tile lane');
 field('completeRound();basilisk.ap=3');
 assert.equal(field('plan(basilisk,10,6)'),undefined,'physical capacity alone cannot cover an unaffordable route');
 assert.equal(field('plan(basilisk,10,7).ap'),2);
 field('basilisk.mechSkills=[AERO_FRAME]');
 assert.equal(field('jumpjetLanding(basilisk,10,6)'),false,'Jumpjet still uses the heavy drive rate');
 assert.equal(await field('basilisk.ap=4;useJumpjet(basilisk,10,6)'),true);
 assert.deepEqual(Array.from(field('[basilisk.ap,basilisk.moveLeft]')),[0,2]);
 console.log('PASS shared AP checkpoint round trip, carryover, recovery cap, attack refunds, tactical ceiling and delayed barrage spend, and chassis mobility versus AP');
})().catch(error=>{console.error(error);process.exitCode=1});
