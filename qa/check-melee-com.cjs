const assert=require('node:assert/strict');
const {run}=require('./sim-harness.cjs')({random:()=>0,reducedMotion:true});
const plain=code=>JSON.parse(run('JSON.stringify('+code+')'));

(async()=>{
 run(`
  createBattle(1,false,false,[0,1]);startBattleCom(20);battle.cover.clear();battle.field={};
  const userMech=battle.units[0],target=battle.units.find(u=>u.team==='enemy'&&!u.kind);
  const blade=weapon('cleaver'),pilot=pilotId(userMech.pilot);
  Object.assign(userMech,{x:4,z:5,ap:14,melee:'cleaver'});
  Object.assign(target,{x:5,z:5,noCounter:true,shield:null});
  Object.assign(target.max,{right:100,left:100,legs:100,body:1000});
  Object.assign(target.hp,{right:45,left:100,legs:46,body:1000});
  const options=()=>comAttackOptions(userMech,target,blade);
  const special=id=>{const option=options().find(o=>o.id===id);return comBoostWeapon(blade,id,option.strike)};
  const volley=id=>planVolley(userMech,target,'body',special(id),false);
  const stock=()=>planVolley(userMech,target,'body',blade,false);
  const install=id=>{save.comPilots={[pilot]:{progress:{[id]:6},installed:[id]}}};
 `);
 assert.ok(run("options().some(o=>o.id==='armSmash')"));
 assert.ok(run("!options().some(o=>o.id==='legSmash')"));
 run('target.hp.legs=45');
 assert.deepEqual(plain("volley('armSmash').impacts"),[{part:'right',amount:45}]);
 assert.deepEqual(plain("volley('legSmash').impacts"),[{part:'legs',amount:45}]);
 run("ruleRandom=()=>.99999");
 assert.equal(run("volley('legSmash').landed"),0,'a Smash can still miss');
 run("ruleRandom=()=>0;target.shield='bulwark-shield';target.hp.left=40;");
 assert.deepEqual(plain("volley('armSmash').impacts"),[{part:'left',amount:40}]);
 assert.ok(run("!options().some(o=>o.id==='legSmash'||o.id==='sweep')"),'the live shield screens legs and body');
 run('delete target.shield;target.hp.left=100;target.hp.right=44;');
 const sweep=plain("volley('sweep')");
 assert.deepEqual(sweep.impacts.map(x=>x.part),['body','right']);
 assert.equal(sweep.impacts[0].amount,Math.round(run('stock().impacts[0].amount')*.55));
 assert.equal(sweep.impacts[1].amount,Math.round(run("attackBudget(userMech,target,'right',blade)")*.55));
 assert.equal(run("volley('meleeExpert').impacts[0].amount"),Math.round(run('stock().impacts[0].amount')*1.3));
 assert.equal(run("volley('meleeExpert2').impacts[0].amount"),Math.round(run('stock().impacts[0].amount')*1.55));
 assert.equal(run("validComLoadout(['meleeExpert','meleeExpert2'],{progress:{meleeExpert:6,meleeExpert2:6}})"),false);
 run("install('legSmash');target.hp.legs=45;");
 assert.match(run("attackPreview(userMech,target,blade)"),/Leg Smash 5% \(LEGS\)/);
 await run("engage(userMech,target,'body',blade)");
 assert.equal(run('target.hp.legs'),0);
 assert.equal(run('userMech.ap'),run('BASE_AP-weaponAP(blade,userMech.training)'));
 assert.equal(run('userMech.attackAPSpent'),run('weaponAP(blade,userMech.training)'));
 assert.equal(run('target.hp.body'),1000,'a successful Smash stays on its limb');
 assert.equal(run('target.alive'),true);
 assert.ok(run("!options().some(o=>o.id==='legSmash')"),'a destroyed limb is ineligible for the chain');
 run("install('guardBreak');target.brace=true;");
 await run("engage(userMech,target,'body',blade)");
 assert.equal(run('target.brace'),false);
 assert.ok(run('validSave(save)'), 'the new routines use the existing save format');
 console.log('PASS melee COM thresholds, shield priority, split hits, rank exclusivity, AP and part destruction');
})().catch(error=>{console.error(error);process.exitCode=1});
